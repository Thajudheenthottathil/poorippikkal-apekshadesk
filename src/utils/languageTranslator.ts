export async function translateActiveDocumentViaServer(params: {
  category: DocumentCategory;
  targetLanguage: DocumentOutputLanguage;
  letterData: MalayalamLetterData;
  gulfCvData: GulfCvData;
  agreementData: RentalAgreementData;
  markListData: TeacherMarkListData;
}): Promise<{
  letterData?: MalayalamLetterData;
  gulfCvData?: GulfCvData;
  agreementData?: RentalAgreementData;
  markListData?: TeacherMarkListData;
}> {
  const res = await fetch('/api/translate-doc', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(params),
  });
  if (!res.ok) {
    throw new Error('Translation API failed');
  }
  return res.json();
}
