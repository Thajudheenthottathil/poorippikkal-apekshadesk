/**
 * Extracts Kerala town/place and district reliably from natural Malayalam prompts:
 * - "എന്റെ പേര് ഷമീർ കെ, തിരൂർ മലപ്പുറം സ്വദേശിയാണ്" -> { place: 'തിരൂർ', district: 'മലപ്പുറം', found: true }
 * - "എന്റെ പേര് രാജേഷ് ബാബു, ഒറ്റപ്പാലം പാലക്കാട്" -> { place: 'ഒറ്റപ്പാലം', district: 'പാലക്കാട്', found: true }
 * - "വാടകക്കാരൻ ഷമീർ അഹമ്മദ്, മഞ്ചേരി. വീട് വാടക കരാർ തയ്യാറാക്കണം." -> { place: 'മഞ്ചേരി', district: 'മലപ്പുറം', found: true }
 */
export function extractKeralaPlaceAndDistrict(rawPrompt: string): {
  place: string;
  district: string;
  found: boolean;
} {
  const prompt = normalizeMalayalamChillaksharam(rawPrompt || '');

  // 1. Check explicit "സ്ഥലം: X (Y)" or "എന്റെ സ്ഥലം X" (excluding "വീട് വാടക കരാർ...")
  const explicitPlaceMatch = prompt.match(
    /(?:എന്റെ സ്ഥലം|സ്ഥലം|സ്വദേശം)\s*[:\-]?\s*([^\n,.;]+?)(?=\s*(?:,|،|ആണ്|ജില്ല|വില്ലേജ്|ഫോൺ|\.|$))/i
  );
  if (explicitPlaceMatch?.[1]?.trim()) {
    const rawPl = explicitPlaceMatch[1]
      .replace(/(?:വീട്\s*)?(?:വാടക\s*കരാർ|കരാർ|അപേക്ഷ|സർട്ടിഫിക്കറ്റ്|തയ്യാറാക്കണം|വേണം).*$/i, '')
      .replace(/\s*(?:ആണ്|സ്വദേശിയാണ്|സ്വദേശി).*$/, '')
      .trim();
    if (rawPl && rawPl.length >= 2) {
      const parenMatch = rawPl.match(/^([^\s(]+)\s*\(([^)]+)\)/);
      if (parenMatch) {
        return {
          district: parenMatch[1].trim(),
          place: parenMatch[2].trim(),
          found: true,
        };
      }
      for (const [town, dist] of KERALA_TOWN_TO_DISTRICT_MAP) {
        if (rawPl.includes(town)) {
          return { place: town, district: dist, found: true };
        }
      }
      for (const dist of KERALA_DISTRICTS_LIST) {
        if (rawPl.includes(dist)) {
          const otherPart = rawPl.replace(dist, '').replace(/[,()\s]+/g, ' ').trim();
          return {
            place: otherPart.length >= 2 ? otherPart : dist,
            district: dist === 'കാസർഗോഡ്' ? 'കാസർകോട്' : dist,
            found: true,
          };
        }
      }
      return { place: rawPl, district: rawPl, found: true };
    }
  }

  // 2. Check known Kerala towns & districts anywhere in the prompt
  let detectedTown = '';
  let mappedDistrict = '';
  for (const [town, dist] of KERALA_TOWN_TO_DISTRICT_MAP) {
    if (prompt.includes(town)) {
      detectedTown = town;
      mappedDistrict = dist;
      break;
    }
  }

  let detectedDistrict = '';
  for (const dist of KERALA_DISTRICTS_LIST) {
    if (prompt.includes(dist)) {
      detectedDistrict = dist === 'കാസർഗോഡ്' ? 'കാസർകോട്' : dist;
      break;
    }
  }

  if (detectedTown) {
    return {
      place: detectedTown,
      district: detectedDistrict || mappedDistrict || detectedTown,
      found: true,
    };
  }

  if (detectedDistrict) {
    return {
      place: detectedDistrict,
      district: detectedDistrict,
      found: true,
    };
  }

  // 3. Check "<Place> സ്വദേശിയാണ് / സ്വദേശി" pattern
  const swadeshiMatch = prompt.match(
    /(?:,\s*|\.\s*|^|\s)([^\s,.;:]+(?:\s+[^\s,.;:]+)?)\s+സ്വദേശി(?:യാണ്|യായ)?/i
  );
  if (swadeshiMatch?.[1]?.trim()) {
    const candidate = swadeshiMatch[1]
      .replace(/^(?:ഞാൻ|എന്റെ|പേര്|അപേക്ഷകൻ)\s+/i, '')
      .trim();
    if (
      candidate.length >= 2 &&
      candidate.length <= 28 &&
      !/വാടക|കരാർ|തയ്യാറാക്കണം|വേണം|സർട്ടിഫിക്കറ്റ്/.test(candidate)
    ) {
      const parts = candidate.split(/\s+/).filter(Boolean);
      if (parts.length >= 2) {
        return { place: parts[0], district: parts[parts.length - 1], found: true };
      }
      return { place: candidate, district: candidate, found: true };
    }
  }

  return { place: 'കേരളം', district: 'കേരളം', found: false };
}

export function convertMalayalamToEnglish(
  text: string,
  allowProperNameTransliteration = true
): string {
  if (!text) return text;
  let result = normalizeMalayalamChillaksharam(text);

  // Clean up any duplicate location tokens even if input already had English "Kerala , Kerala"
  const dedupEnglishLocations = (str: string) =>
    str
      .replace(/\s+,/g, ',')
      .replace(/,\s*,+/g, ',')
      .replace(/\b(Kerala|India)\s*,\s*\1\b/gi, '$1')
      .replace(/\b(Kerala)\s*,\s*(Kerala)\b/gi, '$1')
      .replace(/\s{2,}/g, ' ')
      .trim();

  if (!/[\u0D00-\u0D7F]/.test(result)) {
    return dedupEnglishLocations(result);
  }

  // 0. If the text has mixed Malayalam + English in parentheses like "കൂട്ടായ പ്രവർത്തനം (Team Collaboration)"
  // or "പ്രൊഫഷണൽ സംഗ്രഹം (PROFESSIONAL SUMMARY)", extract the pure English part when converting to English!
  result = result.replace(
    /[\u0D00-\u0D7F\s/&,-]+\(([A-Za-z0-9\s/&.,-]+)\)/g,
    (_match, engInside: string) => engInside.trim()
  );
  if (!/[\u0D00-\u0D7F]/.test(result)) return dedupEnglishLocations(result);

  // 0B. Convert standalone Malayalam single-letter initials (e.g. "ഷമീർ കെ" -> "ഷമീർ K.") before general word map
  const initialTokens = Object.keys(MALAYALAM_STANDALONE_INITIALS_MAP)
    .sort((a, b) => b.length - a.length)
    .join('|');
  const initialRegex = new RegExp(
    `(^|[\\s,.;()])(${initialTokens})\\.?(?=$|[\\s,.;()])`,
    'g'
  );
  result = result.replace(initialRegex, (_m, prefix: string, initMal: string) => {
    const mapped = MALAYALAM_STANDALONE_INITIALS_MAP[initMal];
    return mapped ? `${prefix}${mapped}` : _m;
  });

  // 1. Replace semantic Malayalam phrases & job/education terms first (longest first)
  const sortedSemantic = [...MALAYALAM_TO_ENGLISH_SEMANTIC_MAP].sort(
    (a, b) => b[0].length - a[0].length
  );
  for (const [malPhrase, engMeaning] of sortedSemantic) {
    if (result.includes(malPhrase)) {
      result = result.split(malPhrase).join(engMeaning ? ` ${engMeaning} ` : ' ');
    }
  }
  result = result.replace(/\s{2,}/g, ' ').trim();
  if (!/[\u0D00-\u0D7F]/.test(result)) return dedupEnglishLocations(result);

  // 2. Replace known proper names & places from reverse map (longest first)
  const malKeys = Object.keys(MALAYALAM_TO_ENGLISH_WORD_MAP).sort((a, b) => b.length - a.length);
  for (const mKey of malKeys) {
    if (mKey.length >= 2 && result.includes(mKey)) {
      result = result.split(mKey).join(` ${MALAYALAM_TO_ENGLISH_WORD_MAP[mKey]} `);
    }
  }
  result = result.replace(/\s{2,}/g, ' ').trim();
  if (!/[\u0D00-\u0D7F]/.test(result)) return dedupEnglishLocations(result);

  // 3. For any remaining Malayalam proper nouns/tokens when target is English:
  // If allowProperNameTransliteration is true, transliterate names cleanly.
  // If false, keep semantic English or avoid phonetic Manglish.
  if (!allowProperNameTransliteration) {
    return dedupEnglishLocations(result);
  }

  const malConsonants: Record<string, string> = {
    ക: 'k', ഖ: 'kh', ഗ: 'g', ഘ: 'gh', ങ: 'ng',
    ച: 'ch', ഛ: 'chh', ജ: 'j', ഝ: 'jh', ഞ: 'nj',
    ട: 't', ഠ: 'th', ഡ: 'd', ഢ: 'dh', ണ: 'n',
    ത: 'th', ഥ: 'th', ദ: 'd', ധ: 'dh', ന: 'n',
    പ: 'p', ഫ: 'ph', ബ: 'b', ഭ: 'bh', മ: 'm',
    യ: 'y', ര: 'r', ല: 'l', വ: 'v', ശ: 'sh',
    ഷ: 'sh', സ: 's', ഹ: 'h', ള: 'l', ഴ: 'zh', റ: 'r',
  };
  const malVowels: Record<string, string> = {
    അ: 'A', ആ: 'Aa', ഇ: 'I', ഈ: 'Ee', ഉ: 'U', ഊ: 'Oo',
    ഋ: 'Ri', എ: 'E', ഏ: 'E', ഐ: 'Ai', ഒ: 'O', ഓ: 'O', ഔ: 'Au',
  };
  const malSigns: Record<string, string> = {
    'ാ': 'a', 'ി': 'i', 'ീ': 'ee', 'ു': 'u', 'ൂ': 'oo',
    'ൃ': 'ri', 'െ': 'e', 'േ': 'e', 'ൈ': 'ai', 'ൊ': 'o',
    'ോ': 'o', 'ൗ': 'au', 'ൌ': 'au', '്': '', 'ം': 'm', 'ഃ': 'h',
  };
  const malChillus: Record<string, string> = {
    ൺ: 'n', ൻ: 'n', ർ: 'r', ൽ: 'l', ൾ: 'l', ൿ: 'k',
  };

  let out = '';
  for (let i = 0; i < result.length; i++) {
    const ch = result[i];
    const next = result[i + 1] || '';
    if (malConsonants[ch]) {
      if (malSigns[next] !== undefined) {
        out += malConsonants[ch] + malSigns[next];
        i++;
      } else {
        out += malConsonants[ch] + 'a';
      }
    } else if (malVowels[ch]) {
      out += malVowels[ch];
    } else if (malChillus[ch]) {
      out += malChillus[ch];
    } else if (malSigns[ch] !== undefined) {
      out += malSigns[ch];
    } else if (/[\u0D00-\u0D7F]/.test(ch)) {
      // Skip any remaining Malayalam mark
      continue;
    } else {
      out += ch;
    }
  }
  return dedupEnglishLocations(
    out.replace(/\b([a-z])/g, (m) => m.toUpperCase()).replace(/\s{2,}/g, ' ').trim()
  );
}

function getPhraseTargetValue(
  entry: { ml: string; en: string; ar: string; hi: string; ur?: string; ta?: string },
  targetLang: DocumentOutputLanguage
): string {
  if (targetLang === 'ur') return entry.ur || entry.ar || entry.en;
  if (targetLang === 'ta') return entry.ta || entry.en;
  return entry[targetLang] || entry.en;
}

export function translateSingleStringLocal(
  text: string,
  targetLang: DocumentOutputLanguage,
  isProperName = false
): string {
  if (!text || !text.trim()) return text;
  // Clean any legacy prompt interpolation artifact from CV summary
  const cleanedText = normalizeMalayalamChillaksharam(text)
    .replace(/\s*Detail generated from your request:\s*"[^"]*"\.?\s*/gi, ' ')
    .replace(/\s{2,}/g, ' ')
    .trim();
  if (!cleanedText) return text;

  // Exact match
  for (const entry of PHRASE_MAP) {
    const candidates = [entry.ml, entry.en, entry.ar, entry.hi, entry.ur, entry.ta].filter(
      Boolean
    ) as string[];
    if (candidates.some((c) => c.toLowerCase() === cleanedText.toLowerCase())) {
      return getPhraseTargetValue(entry, targetLang);
    }
  }

  // Substring replacement for known phrases/places
  let result = cleanedText;
  for (const entry of PHRASE_MAP) {
    const targetVal = getPhraseTargetValue(entry, targetLang);
    for (const srcKey of ['ml', 'en', 'ar', 'hi', 'ur', 'ta'] as const) {
      if (srcKey === targetLang) continue;
      const srcVal = entry[srcKey];
      if (srcVal && srcVal.length >= 4 && result.includes(srcVal)) {
        result = result.split(srcVal).join(targetVal);
      }
    }
  }

  // Bi-directional script enforcement:
  // When target language is English ('en'), convert all Malayalam semantic phrases, places & proper names to pure English
  // (NOTE: When target language is Malayalam, we strictly preserve English Survey numbers, PAN cards, codes, and acronyms verbatim)
  if (targetLang === 'en' && /[\u0D00-\u0D7F]/.test(result)) {
    result = convertMalayalamToEnglish(result, isProperName);
  }

  return result;
}

export function applyLocalLanguageConversionToCv(
  cv: GulfCvData,
  targetLang: DocumentOutputLanguage
): GulfCvData {
  const tr = (s: string) => translateSingleStringLocal(s, targetLang, false);
  const trName = (s: string) => translateSingleStringLocal(s, targetLang, true);
  return {
    ...cv,
    fullName: trName(cv.fullName),
    jobTitle: tr(cv.jobTitle),
    currentLocation: tr(cv.currentLocation),
    visaStatus: tr(cv.visaStatus),
    drivingLicense: tr(cv.drivingLicense),
    passportNumber: tr(cv.passportNumber),
    maritalStatus: tr(cv.maritalStatus),
    languages: (cv.languages || []).map(tr),
    professionalSummary: tr(cv.professionalSummary),
    workExperience: (cv.workExperience || []).map((exp) => ({
      ...exp,
      role: tr(exp.role),
      company: tr(exp.company),
      location: tr(exp.location),
      duration: tr(exp.duration),
      highlights: (exp.highlights || []).map(tr),
    })),
    education: (cv.education || []).map((edu) => ({
      ...edu,
      degree: tr(edu.degree),
      institution: tr(edu.institution),
      year: tr(edu.year),
    })),
    coreSkills: (cv.coreSkills || []).map(tr),
    declaration: tr(cv.declaration),
    cvPlace: cv.cvPlace ? tr(cv.cvPlace) : cv.cvPlace,
    signatureName: cv.signatureName ? trName(cv.signatureName) : trName(cv.fullName),
  };
}

export function applyLocalLanguageConversionToLetter(
  letter: MalayalamLetterData,
  targetLang: DocumentOutputLanguage
): MalayalamLetterData {
  const tr = (s: string) => translateSingleStringLocal(s, targetLang);
  const trName = (s: string) => translateSingleStringLocal(s, targetLang, true);
  return {
    ...letter,
    documentHeading: tr(letter.documentHeading),
    senderName: trName(letter.senderName),
    senderAddress: trName(letter.senderAddress),
    recipientTitle: tr(letter.recipientTitle),
    recipientOffice: tr(letter.recipientOffice),
    recipientPlace: trName(letter.recipientPlace),
    subject: tr(letter.subject),
    salutation: tr(letter.salutation),
    bodyParagraphs: (letter.bodyParagraphs || []).map(tr),
    closingPhrase: tr(letter.closingPhrase),
    place: trName(letter.place),
    enclosures: (letter.enclosures || []).map(tr),
    structuredFields: letter.structuredFields
      ? letter.structuredFields.map((f) => ({
          ...f,
          label: tr(f.label),
          value: tr(f.value),
        }))
      : letter.structuredFields,
  };
}

